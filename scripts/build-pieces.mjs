// Downloads the piece sets from Lichess into public/pieces/<set>/ and writes
// src/pieces.css, which picks a set from the data-pieces attribute on <html>.
// Licences are listed in https://github.com/lichess-org/lila/blob/master/COPYING.md
import { mkdirSync, writeFileSync } from 'node:fs'

const sets = ['staunty', 'cardinal', 'fresca', 'california', 'maestro', 'cburnett']
const roles = { P: 'pawn', N: 'knight', B: 'bishop', R: 'rook', Q: 'queen', K: 'king' }
const colors = { w: 'white', b: 'black' }
const base = 'https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/'

let css = '/* Generated by scripts/build-pieces.mjs. Do not edit. */\n'
for (const set of sets) {
  mkdirSync(`public/pieces/${set}`, { recursive: true })
  for (const [c, color] of Object.entries(colors)) {
    for (const [r, role] of Object.entries(roles)) {
      const res = await fetch(`${base}${set}/${c}${r}.svg`)
      if (!res.ok) throw new Error(`${set}/${c}${r}.svg: HTTP ${res.status}`)
      writeFileSync(`public/pieces/${set}/${c}${r}.svg`, await res.text())
      css += `[data-pieces='${set}'] .cg-wrap piece.${role}.${color} { background-image: url('/pieces/${set}/${c}${r}.svg'); }\n`
    }
  }
}
writeFileSync('src/pieces.css', css)
console.log(`Wrote ${sets.length} piece sets`)
